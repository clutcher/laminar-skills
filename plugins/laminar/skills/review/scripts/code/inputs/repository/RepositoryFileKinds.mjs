export const MAX_MINIFIED_LINE = 1000;

const FOLDERS_NEVER_WALKED = new Set(["node_modules", ".git", "target", "build", "dist", "vendor", ".venv", "venv", ".claude"]);

export const isAFolderNeverWalked = name => FOLDERS_NEVER_WALKED.has(name);

const MINIFIED_NAME_PATTERN = /\.min\.(?:js|css)$|\.bundle\.js$/;
const GENERATED_MARKERS = [/@Generated\b/, /DO NOT EDIT/i, /auto-?generated/i, /Code generated by/i];
const GENERATED_PATH_PATTERN = /(^|\/)(generated|gen|build|dist|node_modules|target)(\/|$)|\.g\.[a-z]+$|_pb2?\.[a-z]+$/i;

const measureLongestLine = lines => lines.reduce((longest, line) => Math.max(longest, line.length), 0);

export const isMinified = (given, lines) => MINIFIED_NAME_PATTERN.test(given) || measureLongestLine(lines) > MAX_MINIFIED_LINE;

export const isGeneratedFile = (filePath, lines) =>
  GENERATED_PATH_PATTERN.test(filePath) || (lines || []).slice(0, 20).some(line => GENERATED_MARKERS.some(pattern => pattern.test(line)));

export const VENDORED_PATH_PATTERN = /(?:^|\/)(?:vendor|third_party|node_modules)\//;

export const isVendored = filePath => VENDORED_PATH_PATTERN.test(filePath);

export const DECLARATION_FILE_PATTERN = /\.d\.[cm]?ts$/;

export const describesOutsideCode = filePath => isVendored(filePath) || DECLARATION_FILE_PATTERN.test(filePath);
